# Build site\data.js (approved episodes, published) and site\drafts.js (drafts, local preview only, gitignored)
$ErrorActionPreference = 'Stop'
$base = Split-Path -Parent $PSScriptRoot
$utf8 = New-Object Text.UTF8Encoding $false
$pub = @(); $drafts = @()
Get-ChildItem "$base\episodes\*.json" | Sort-Object Name -Descending | ForEach-Object {
  $txt = [IO.File]::ReadAllText($_.FullName, [Text.Encoding]::UTF8)
  try {
    $obj = $txt | ConvertFrom-Json
    if (-not $obj.date -or -not $obj.panels) { throw 'missing date/panels' }
    if ($obj.status -eq 'approved') { $pub += $txt.Trim() } else { $drafts += $txt.Trim() }
  } catch {
    Write-Warning ("skip {0}: {1}" -f $_.Name, $_.Exception.Message)
  }
}
$head = "// generated by scripts/build.ps1 - do not edit`n"
[IO.File]::WriteAllText("$base\site\data.js", $head + "window.EPISODES = [`n" + ($pub -join ",`n") + "`n];`n", $utf8)
[IO.File]::WriteAllText("$base\site\drafts.js", $head + "window.DRAFTS = [`n" + ($drafts -join ",`n") + "`n];`n", $utf8)
Write-Output ("built: {0} published, {1} drafts" -f $pub.Count, $drafts.Count)
